    private static final String prefix = "img/emoji/";

    private static final String suffix = ".svg";

    private final String path;

    private final  EmojiCategory category;

    private final String description;

    Emoji(EmojiCategory category, String utf8Code, String description)
    {
        this.category = category;

        this.path = prefix +utf8Code +suffix;

        this.description = description;
    }

    public String getPath() {return this.path; }

    public String getDescription() { return this.description; }

    public EmojiCategory getCategory() { return this.category; }

