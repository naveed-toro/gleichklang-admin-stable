<a name="a4"></a>
<b>4. Effektive Teilnahme bei Gleichklang</b>

<b>- Freier Text</b>
Es ist sehr wichtig, dass Sie in Ihrem Profil auch einen freien Text einstellen. Sollten Sie dies noch nicht getan haben, raten wir Ihnen, dies umgehend nachzuholen. Die Vermittlungschancen von Personen mit freiem Text sind sehr viel höher, als wenn auf einen freien Text verzichtet wird. Wer keinen freien Text einstellt, erhält nur wenig Resonanz. Es ist nicht notwendig, Romane zu schreiben, aber ein paar Sätze zur eigenen Person und wonach Sie suchen, wären für vorgeschlagene Mitglieder eine wichtige Information. Sie können einen freien Text hinzufügen, indem Sie im Teilnahmebereich auf "Partnerschaft" bzw. "Freundschaft" und anschließend auf "Freie Selbstschilderung" klicken.

<b>- Foto</b>
Die Einstellung eines Fotos erhöht die Resonanz deutlich. Sie können mehrere Fotos, organisiert in verschiedenen Galerien, einstellen. Bitte stellen Sie keine pornografischen Fotos ein. Wenn Sie Schwierigkeiten bei der Foto-Einstellung haben, senden Sie uns die Fotos an: fotos@gleichklang.de. Fotos bzw. Galerien können auch individuell für bestimmte Personen freigeschaltet werden. Achtung: Ihr Profilbild (auch Avatar genannt) ist völlig unabhängig von den Galeriebildern und kann stets von allen Ihren Kontakten gesehen werden.

<b>- Such-Einstellungen und Vorschläge</b>
Es gibt bestimmte Einstellungen, die die Vorschlagsanzahl naturgemäß stark reduzieren. Diese sollten Sie also nur dann machen, wenn sie auch erforderlich sind. Zu einer starken Reduktion der Vorschlagsanzahl kommt es, wenn Sie eine Reihe von Akzeptanzanforderungen als WICHTIG angegeben haben, wie Akzeptanz für körperliche oder psychische Erkrankungen oder Behinderungen, HIV, Intersexualität, Transsexualität, Bisexualität, Beziehung zu Dritt oder mehr. Wenn für Sie diese Akzeptanzen tatsächlich bedeutsam sind, sollten Sie die Akzeptanz natürlich trotzdem als wichtig einstellen. Denn so finden wir einen passenden Vorschlag. Es können aber in solchen Fällen längere Wartezeiten entstehen. Gerade wenn Sie besonders seltene Suchen eingeben (z.B. auch Veganer) empfiehlt es sich, wenn irgend möglich, geografisch weiträumig zu suchen, da ansonsten sich die Suchzeit ebenfalls deutlich verlängern wird. Wenn Sie bei der BDSM Suche NUR eingeben, werden ausschließlich Personen vorgeschlagen, die mindestens ein AUCH angegeben haben. Daraus ergibt sich entsprechend ebenfalls eine deutliche Reduktion der Vorschlagsanzahl, die aber sinnvoll ist, wenn Sie die richtige Eingabe gemacht haben. Wenn Sie bei der BDSM Suche ein AUCH eingeben, ergibt sich ebenfalls eine Reduktion der Vorschlagsanzahl, da alle Mitglieder ausfallen, die NEIN, AUF KEINEN FALL angegeben haben. Geben Sie also ein NUR oder AUCH bei BDSM nur dann ein, wenn Ihnen dies auch wichtig ist. Bei dem gesuchten Körpertypus sollten Sie diesen keineswegs allein auf normal einschränken, sondern mindestens zusätzlich eine weitere Kategorie, wie schlank oder ein paar Pfunde mehr, angeben. Insgesamt gilt, dass weichere Kriterien, wie VIELLEICHT, EHER JA, oder EHER NEIN zu mehr Vorschlägen führen als härtere Kriterien, wie JA, UNBEDINGT, NEIN oder AUF KEINEN FALL. Eine bedeutsame Auswirkung auf die Vorschlagsanzahl hat ebenfalls allgemein die Größe des geografischen Suchbereiches, den Sie nutzen. Wir stellen fest, dass am schnells