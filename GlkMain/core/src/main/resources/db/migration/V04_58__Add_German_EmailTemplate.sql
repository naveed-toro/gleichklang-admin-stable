<b>- Veränderungen Ihres Profils</b>
Unter "Mein Profil bearbeiten" können Sie Ihre Angaben zu Person, Aussehen, Hobbys, Ihren Sucheinstellungen sowie den freien Text jederzeit verändern. Sie können ebenfalls jederzeit Fotos hochladen oder Fotos entfernen. Wenn Sie an der Partnerschafts- und Freundschaftsvermittlung teilnehmen, können Sie unterschiedliche Fotos und freie Texte für diese beiden Vermittlungsrubriken verfassen bzw. hochladen.

<b>- Einstufung der Vorschläge</b>
Bitte stufen Sie jeden erhaltenen Vorschlag danach ein, ob Sie ihn interessant finden. Denn nur wenn Sie diese Einstufung vornehmen, können wir unsere Vermittlungsprozedur kontinuierlich verbessern. Außerdem wird den anderen Mitgliedern angezeigt, wenn Sie sie als interessant einstufen, was eine wichtige Information ist, die die Kommunikation erleichtert. Es wird dagegen nicht angezeigt, wenn Sie ein anderes Mitglied als zu ignorieren eingestuft haben. In jedem Fall ist es für eine erfolgreiche Teilnahme äußerst wichtig, dass Sie die Einstufungen vornehmen. Sie können Einstufungen jederzeit später wieder korrigieren, wenn Sie zu einer anderen Einschätzung gelangen.

<b>- Auf Vorschläge reagieren</b>
Wir machen immer wieder die Erfahrung, dass Mitglieder zunächst einmal nicht reagieren, sondern abwarten, ob das andere Mitglied reagiert. Ergebnis ist nicht selten: Niemand tut den ersten Schritt und ein Kontakt kommt nicht zustande. Manche warten auch mit den Einstufungen, bis sie durch das andere Mitglied eingestuft werden. Auch hier ist das Ergebnis: Eine Einstufung bleibt aus und ein Kontakt entsteht nicht. Dies ist schade. Wir raten Ihnen daher dringend, nicht abzuwarten, sondern sich bei einem vorgeschlagenen Mitglied zu melden. Wieder gilt: Sie brauchen ja in der ersten Mail keinen Roman zu schreiben, ein paar Zeilen fallen Ihnen bestimmt ein!

<b>- Teilnahmeverlängerung</b>
Die Teilnahmezeit beträgt ${durationInMonths} Monate. Mit Ablauf der Teilnahmezeit tritt eine automatische Teilnahmeverlängerung für ${autoRenewalDurationInMonths} Monate in Kraft. Wenn Sie sicher sind, dass Sie die automatische Teilnahmeverlängerung nicht nutzen wollen, dann teilen Sie uns das bitte unter Angabe Ihres Pseudonyms durch Senden einer Mail an die Adresse "anfragen@gleichklang.de" mit. Wir raten Ihnen allerdings davon ab, die automatische Verlängerung abzustellen. In der Regel dauern Partnerschafts- und Freundschaftssuche länger als die gebuchte Teilnahmezeit. Diejenigen, bei denen die Verlängerung automatisch erfolgt, werden ohne die Prozedur einer Neuanmeldung nahtlos weiter teilnehmen können. Wenn Sie die Verlängerung abstellen und Ihre Teilnahme ausläuft, wird dagegen ein kompletter Neuanfang erforderlich sein, was kostspieliger ist. Auch nach erfolgter Abschaltung der automatischen Verlängerung können Sie diese übrigens wieder im Teilnahmbereich unter "Meine Teilnahme" -> "Abonnement" einschalten.

<b>- Nutzung aller Vermittlungsarten</b>
Gleichklang offeriert eine Partner-, Freundschafts- und Reisepartnervermittlung. Die Reisepartnervermittlung ist dabei ein Unterbereich der Freundschaftsvermittlung. Wenn Sie bisher nur an einer oder zwei der Vermittlungen teilnehmen, können Sie dies jederzeit im Teilnahmebereich erweitern. Es ist ganz einfach, Ihre Teilnahme zu erweitern: Um zusätzlich an der Freundschafts- oder Partnervermittlung teilzunehmen, gehen Sie im Teilnahmebereich auf "Meine Teilnahme", "Abonnement" und "Erweiterungen". Wählen Sie hier die Option "Gratis. Erweiterung auf die Vermittlungskategorien Partnerschaft und Freundschaft". Um die Vermittlung für einzelne Kategorien aus- und einzuschalten, gehen Sie im Teilnahmebereich auf "Meine Teilnahme", "Abonnement" und "Aktive Rubriken". Durch ein einfaches Kreuz können Sie nun Ihre Suche erweitern oder einschränken. Wenn Sie bereits an der Freundschaftsvermittlung teilnehmen und nun auch noch eine Reisefreundschaft suchen wollen, gehen Sie bitte im Teilnahmebereich unter "Freundschaft" auf "Was Sie suchen" und dort "Verreisen gemeinsam" und geben Sie dort durch ein einfaches Kreuz an, dass Sie auch eine Reisefreundschaft suchen. Wir raten Ihnen, alle Vermittlungen zu nutzen, die für Sie interessant sind!


